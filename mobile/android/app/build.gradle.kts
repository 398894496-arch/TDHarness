// Release signing from keystore.properties beside this project (never committed): storeFile, storePassword, keyAlias,
// keyPassword. Without it a release build is left unsigned.
val signing = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "cn.tdharness.mobile"
    compileSdk = 35

    defaultConfig {
        applicationId = "cn.tdharness.mobile"
        minSdk = 26
        targetSdk = 35
        versionCode = (project.findProperty("tdhVersionCode") as String?)?.toInt() ?: 1
        versionName = "1.2"
    }

    signingConfigs {
        if (signing.getProperty("storeFile") != null) {
            create("release") {
                storeFile = file(signing.getProperty("storeFile"))
                storePassword = signing.getProperty("storePassword")
                keyAlias = signing.getProperty("keyAlias")
                keyPassword = signing.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures { compose = true; buildConfig = true }
}

